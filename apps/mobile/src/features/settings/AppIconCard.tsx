import { Check, ChevronRight } from 'lucide-react-native'
import { useState } from 'react'
import { useTranslation } from 'react-i18next'
import { Image, type ImageSourcePropType, Modal, Pressable, ScrollView, StyleSheet } from 'react-native'
import { useSafeAreaInsets } from 'react-native-safe-area-context'
import { makeStyles, radius, resolveThemeName, space, useTheme, useThemeStore } from '@/core/theme'
import { Button, Card, Text } from '@/ui'
import type { AppIconPreference } from './app-icon'
import { type AppIconRow, appIconPreviewKey, appIconRowLabel, appIconRows } from './app-icon-picker'
import { setAppIconPreference, useAppIconStore } from './app-icon-store'

/** One preview PNG per concrete icon (not `matchTheme`, which shows the resolved theme's); generated by scripts/icons.mts. */
const PREVIEWS: Record<Exclude<AppIconPreference, 'matchTheme'>, ImageSourcePropType> = {
  original: require('../../../assets/icon.png'),
  dark: require('../../../assets/app-icon/dark.png'),
  light: require('../../../assets/app-icon/light.png'),
  dracula: require('../../../assets/app-icon/dracula.png'),
  mocha: require('../../../assets/app-icon/mocha.png'),
  latte: require('../../../assets/app-icon/latte.png'),
}

/** Settings → App icon: a select row opening a modal with the scrollable icon list. */
export function AppIconCard() {
  const { t } = useTranslation()
  const preference = useAppIconStore((s) => s.preference)
  const [open, setOpen] = useState(false)
  const rowLabel = appIconRowLabel(preference, t)
  return (
    <Card>
      <Pressable
        accessibilityRole="button"
        accessibilityLabel={rowLabel}
        onPress={() => setOpen(true)}
        style={({ pressed }) => [layout.row, pressed && layout.pressed]}
      >
        <Text weight="bold" style={layout.flex}>
          {rowLabel}
        </Text>
        <AppIconRowChevron />
      </Pressable>
      <AppIconPickerSheet visible={open} onClose={() => setOpen(false)} />
    </Card>
  )
}

function AppIconRowChevron() {
  const { colors } = useTheme()
  return <ChevronRight size={16} color={colors.textDim} />
}

function AppIconPickerSheet({ visible, onClose }: { visible: boolean; onClose: () => void }) {
  const { t } = useTranslation()
  const styles = useStyles()
  const insets = useSafeAreaInsets()
  const preference = useAppIconStore((s) => s.preference)
  const rows = appIconRows(preference, t)
  return (
    <Modal visible={visible} transparent animationType="slide" onRequestClose={onClose}>
      <Pressable style={styles.backdrop} onPress={onClose}>
        <Pressable style={[styles.sheet, { paddingBottom: insets.bottom + space.md }]}>
          <Text weight="bold">{t('settings.appIcon.title')}</Text>
          <ScrollView style={layout.list} contentContainerStyle={layout.listContent}>
            {rows.map((row) => (
              <AppIconOptionRow
                key={row.choice}
                row={row}
                onPress={() => void setAppIconPreference(row.choice)}
              />
            ))}
          </ScrollView>
          <Button label={t('settings.appIcon.done')} variant="ghost" onPress={onClose} />
        </Pressable>
      </Pressable>
    </Modal>
  )
}

function AppIconOptionRow({ row, onPress }: { row: AppIconRow; onPress: () => void }) {
  const { colors } = useTheme()
  const styles = useStyles()
  const resolvedTheme = useThemeStore((s) => resolveThemeName(s.preference, s.system))
  const preview = PREVIEWS[appIconPreviewKey(row.choice, resolvedTheme)]
  return (
    <Pressable
      accessibilityRole="radio"
      accessibilityState={{ selected: row.selected }}
      accessibilityLabel={row.label}
      onPress={onPress}
      style={({ pressed }) => [styles.optionRow, pressed && layout.pressed]}
    >
      <Image source={preview} style={styles.swatch} />
      <Text weight={row.selected ? 'bold' : 'regular'} style={layout.flex}>
        {row.label}
      </Text>
      {row.selected ? <Check size={18} color={colors.accentText} /> : null}
    </Pressable>
  )
}

const layout = StyleSheet.create({
  flex: { flex: 1 },
  row: { flexDirection: 'row', alignItems: 'center', gap: space.sm },
  pressed: { opacity: 0.7 },
  list: { maxHeight: 420 },
  listContent: { gap: space.xs },
})

const useStyles = makeStyles((theme) => ({
  backdrop: { flex: 1, backgroundColor: theme.colors.backdrop, justifyContent: 'flex-end' },
  sheet: {
    backgroundColor: theme.colors.surface,
    borderTopLeftRadius: radius.lg,
    borderTopRightRadius: radius.lg,
    padding: space.xl,
    gap: space.md,
    borderTopWidth: 1,
    borderColor: theme.colors.border,
  },
  optionRow: {
    flexDirection: 'row',
    alignItems: 'center',
    gap: space.md,
    paddingVertical: space.sm,
    paddingHorizontal: space.xs,
    borderRadius: radius.md,
  },
  swatch: {
    width: 40,
    height: 40,
    borderRadius: radius.sm,
    borderWidth: 1.5,
    borderColor: theme.colors.border,
  },
}))
