import { type Locale, localeFromPath } from './i18n/locale.ts'
import { type InstallScriptName, parseRef } from './install.ts'

/** Expo Updates server the `/api/updates/*` routes are forwarded to (it can move without new builds). */
export const UPDATES_ORIGIN = 'https://maarkn.dev'
export const UPDATES_UPSTREAM_PATH = '/api/claude-remote/updates/'
export const UPDATES_PATH = '/api/updates/'

/** File names published by `scripts/ios-link.mts`; nothing else is served under a token. */
export const IOS_FILES = ['index.html', 'manifest.plist', 'RemoteHarness.ipa'] as const
/** Random path segment generated by the publisher (capability URL). */
const TOKEN = /^[A-Za-z0-9_-]{24,64}$/

/** The installers by name; `/install` picks one from the client (see install.ts). */
export const INSTALLERS = ['install.sh', 'install.ps1'] as const satisfies readonly InstallScriptName[]

const DOCS = /^\/docs(?:\/([A-Za-z0-9-]+))?\/?$/
const LOCALIZED_DOCS = /^\/([^/]+)\/docs(?:\/([A-Za-z0-9-]+))?\/?$/

export type Route =
  | { kind: 'updates'; url: string }
  | { kind: 'ios'; key: string }
  /** The landing page; `locale: null` negotiates from `Accept-Language`. */
  | { kind: 'page'; locale: Locale | null }
  /** A documentation page (`index` is `/docs/` itself); whether the slug exists is the renderer's call. */
  | { kind: 'doc'; locale: Locale | null; slug: string }
  | { kind: 'sitemap' }
  | { kind: 'robots' }
  | { kind: 'favicon' }
  /** `/install`: the script or the page, depending on who asks; `ref` from `?ref=`. */
  | { kind: 'install'; ref: string | null }
  | { kind: 'script'; name: InstallScriptName; ref: string | null }
  /** `?ref=` that is not a plain branch or tag name. */
  | { kind: 'bad-ref' }
  | { kind: 'not-found' }

/** The slug a docs path names; the index has no segment, and `index` spelled out is not a page. */
function docSlug(segment: string | undefined): string | null {
  if (segment === undefined) return 'index'
  return segment === 'index' ? null : segment
}

/** Where a request to remoteharness.app goes, from its path and query. */
export function route(pathname: string, search = ''): Route {
  if (pathname.startsWith(UPDATES_PATH)) {
    const rest = pathname.slice(UPDATES_PATH.length)
    if (!rest || rest.includes('..')) return { kind: 'not-found' }
    return { kind: 'updates', url: `${UPDATES_ORIGIN}${UPDATES_UPSTREAM_PATH}${rest}${search}` }
  }
  const ios = /^\/ios\/([^/]+)\/([^/]*)$/.exec(pathname)
  if (ios) {
    const [, token = '', file = ''] = ios
    const name = file === '' ? 'index.html' : file
    if (TOKEN.test(token) && (IOS_FILES as readonly string[]).includes(name)) {
      return { kind: 'ios', key: `${token}/${name}` }
    }
    return { kind: 'not-found' }
  }
  if (pathname === '/' || pathname === '/index.html') return { kind: 'page', locale: null }
  const docs = DOCS.exec(pathname)
  if (docs) {
    const slug = docSlug(docs[1])
    return slug ? { kind: 'doc', locale: null, slug } : { kind: 'not-found' }
  }
  const localizedDocs = LOCALIZED_DOCS.exec(pathname)
  if (localizedDocs) {
    const locale = localeFromPath(`/${localizedDocs[1] ?? ''}`)
    const slug = docSlug(localizedDocs[2])
    return locale && slug ? { kind: 'doc', locale, slug } : { kind: 'not-found' }
  }
  const locale = localeFromPath(pathname)
  if (locale) return { kind: 'page', locale }
  if (pathname === '/sitemap.xml') return { kind: 'sitemap' }
  if (pathname === '/robots.txt') return { kind: 'robots' }
  if (pathname === '/favicon.svg' || pathname === '/favicon.ico') return { kind: 'favicon' }
  const installer = pathname.slice(1)
  const isScript = (INSTALLERS as readonly string[]).includes(installer)
  if (isScript || pathname === '/install' || pathname === '/install/') {
    const ref = parseRef(search)
    if (ref === false) return { kind: 'bad-ref' }
    return isScript ? { kind: 'script', name: installer as InstallScriptName, ref } : { kind: 'install', ref }
  }
  return { kind: 'not-found' }
}
